#!/usr/bin/env bash
# Sets up this computer for development with agents. Safe to run again.
#
#   1. Links every skill from skills/ into the global skill folders of the agents.
#   2. Sets the global git author. Asks in a terminal, config.env holds the defaults.
#   3. Adds agent tooling files to the global git ignore file.
#   4. Turns off commit and pull request attribution in Claude Code.
#   5. Adds Claude Code session hooks that run sync.sh (see sync.sh).
#   6. Links agent files stored in projects/ into the local project checkouts.
set -euo pipefail

root=$(cd "$(dirname "$0")" && pwd)
# shellcheck source=config.env
source "$root/config.env"

echo "== Skills"
for target in "$HOME/.claude/skills" "$HOME/.agents/skills"; do
  mkdir -p "$target"
  for skill in "$root"/skills/*/; do
    link="$target/$(basename "$skill")"
    if [ -e "$link" ] && [ ! -L "$link" ]; then
      echo "skip $link: a real folder is in the way"
      continue
    fi
    ln -sfn "${skill%/}" "$link"
    echo "linked $link"
  done
done

echo "== Project store"
# The global ignore hides agent files everywhere; projects/ must keep them.
mkdir -p "$root/projects"
{
  echo "# Generated by install.sh. Agent files are the point of this folder."
  grep -v '^#' "$root/skills/repo-cleanup/gitignore-agents" | sed 's/^/!/'
} >"$root/projects/.gitignore"
echo "updated $root/projects/.gitignore"

echo "== Git author"
# Asks when run in a terminal; Enter keeps the value from config.env.
if [ -t 0 ]; then
  read -r -p "Author name [$GIT_NAME]: " answer
  GIT_NAME=${answer:-$GIT_NAME}
  read -r -p "Author email [$GIT_EMAIL]: " answer
  GIT_EMAIL=${answer:-$GIT_EMAIL}
fi
git config --global user.name "$GIT_NAME"
git config --global user.email "$GIT_EMAIL"
echo "$(git config --global user.name) <$(git config --global user.email)>"

echo "== Global git ignore"
ignore=$(git config --global core.excludesfile || true)
ignore=${ignore:-${XDG_CONFIG_HOME:-$HOME/.config}/git/ignore}
ignore=${ignore/#\~/$HOME}
mkdir -p "$(dirname "$ignore")"
touch "$ignore"
begin='# >>> murpiano-dx'
end='# <<< murpiano-dx'
sed -i "/^$begin\$/,/^$end\$/d" "$ignore"
{
  echo "$begin"
  grep -v '^#' "$root/skills/repo-cleanup/gitignore-agents"
  echo "$end"
} >>"$ignore"
echo "updated $ignore"

echo "== Project links"
bash "$root/sync.sh" link

echo "== Claude Code attribution and session hooks"
settings="$HOME/.claude/settings.json"
mkdir -p "$(dirname "$settings")"
[ -f "$settings" ] || echo '{}' >"$settings"
python3 - "$settings" "$root/sync.sh" <<'PY'
import json, sys
path = sys.argv[1]
with open(path) as f:
    data = json.load(f)
data["attribution"] = {"commit": "", "pr": "", "sessionUrl": False}

# Session hooks that keep project agent files in murpiano-dx. Old entries are replaced.
sync = sys.argv[2]
hooks = data.setdefault("hooks", {})
for event, mode in (("SessionStart", "start"), ("SessionEnd", "end")):
    groups = [
        g for g in hooks.get(event, [])
        if not any(sync in h.get("command", "") for h in g.get("hooks", []))
    ]
    groups.append({"hooks": [{"type": "command", "command": f'bash "{sync}" {mode}', "timeout": 60}]})
    hooks[event] = groups
with open(path, "w") as f:
    json.dump(data, f, indent=2, ensure_ascii=False)
    f.write("\n")
PY
echo "updated $settings"
