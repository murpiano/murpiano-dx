#!/usr/bin/env bash
# Sets up this computer for development with agents. Safe to run again.
#
#   1. Links every skill from skills/ into the global skill folders of the agents.
#   2. Sets the global git author. Asks in a terminal, config.env holds the defaults.
#   3. Saves the release token for automatic releases. Asks in a terminal.
#   4. Adds agent tooling files to the global git ignore file.
#   5. Turns off commit and pull request attribution in Claude Code.
#   6. Adds Claude Code session hooks that run sync.sh (see sync.sh).
#   7. Links agent files stored in projects/ into the local project checkouts.
#   8. Installs global agent rules (global/agent-rules.md) and the 50% autocompact threshold.
set -euo pipefail

root=$(cd "$(dirname "$0")" && pwd)
# shellcheck source=config.env
source "$root/config.env"

echo "== Skills"
target="$HOME/.claude/skills"
mkdir -p "$target"
for skill in "$root"/skills/*/; do
  link="$target/$(basename "$skill")"
  if [ -e "$link" ] && [ ! -L "$link" ]; then
    echo "skip $link: a real folder is in the way"
    continue
  fi
  ln -sfn "${skill%/}" "$link"
  echo "linked $link"
done

echo "== Project store"
# The global ignore hides agent files everywhere; projects/ must keep them.
mkdir -p "$root/projects"
{
  echo "# Generated by install.sh. Agent files are the point of this folder."
  grep -v '^#' "$root/skills/repo-cleanup/gitignore-agents" | sed 's/^/!/'
} >"$root/projects/.gitignore"
echo "updated $root/projects/.gitignore"

echo "== Git author"
# Asks when run in a terminal; Enter keeps the value from config.env.
if [ -t 0 ]; then
  read -r -p "Author name [$GIT_NAME]: " answer
  GIT_NAME=${answer:-$GIT_NAME}
  read -r -p "Author email [$GIT_EMAIL]: " answer
  GIT_EMAIL=${answer:-$GIT_EMAIL}
fi
git config --global user.name "$GIT_NAME"
git config --global user.email "$GIT_EMAIL"
echo "$(git config --global user.name) <$(git config --global user.email)>"

echo "== Release token"
# Personal GitHub token for automatic releases (skills/repo-release/rules.md, section 4).
# Stored only in this file and in the RELEASE_TOKEN secret of repositories with releases.
token_file="$HOME/.config/murpiano-dx/release-token"
if [ -t 0 ]; then
  if [ -s "$token_file" ]; then
    prompt="Release token [saved, Enter keeps it]: "
  else
    prompt="Release token [none, Enter skips]: "
  fi
  echo "Input is hidden: paste the token and press Enter."
  read -rs -p "$prompt" token
  echo
  token=$(printf '%s' "$token" | tr -d '[:space:]')
  if [ -n "$token" ]; then
    echo "received ${#token} characters"
    login=$(GH_TOKEN=$token gh api user -q .login 2>/dev/null) || login=""
    if ! [[ "$login" =~ ^[A-Za-z0-9-]+$ ]]; then
      echo "GitHub rejected this token; nothing saved. Run install.sh again to retry."
      unset token
    else
      echo "token belongs to $login"
    fi
  fi
  if [ -n "${token:-}" ]; then
    mkdir -p "$(dirname "$token_file")"
    (umask 077 && printf '%s' "$token" >"$token_file")
    unset token
    echo "saved $token_file"
    echo "updating RELEASE_TOKEN in repositories with releases"
    for repo in $(gh repo list "$GITHUB_OWNER" --limit 500 --json nameWithOwner -q '.[].nameWithOwner' 2>/dev/null); do
      state=$(gh variable get RELEASES -R "$repo" 2>/dev/null) || continue
      if [ "$state" = on ] || [ "$state" = paused ]; then
        gh secret set RELEASE_TOKEN -R "$repo" <"$token_file" && echo "  $repo"
      fi
    done
  fi
fi
[ -s "$token_file" ] && echo "token present" || echo "no token: automatic releases cannot start"

echo "== Global git ignore"
ignore=$(git config --global core.excludesfile || true)
ignore=${ignore:-${XDG_CONFIG_HOME:-$HOME/.config}/git/ignore}
ignore=${ignore/#\~/$HOME}
mkdir -p "$(dirname "$ignore")"
touch "$ignore"
begin='# >>> murpiano-dx'
end='# <<< murpiano-dx'
sed -i "/^$begin\$/,/^$end\$/d" "$ignore"
{
  echo "$begin"
  grep -v '^#' "$root/skills/repo-cleanup/gitignore-agents"
  echo "$end"
} >>"$ignore"
echo "updated $ignore"

echo "== Project links"
bash "$root/sync.sh" link

echo "== Claude Code attribution and session hooks"
settings="$HOME/.claude/settings.json"
mkdir -p "$(dirname "$settings")"
[ -f "$settings" ] || echo '{}' >"$settings"
python3 - "$settings" "$root/sync.sh" <<'PY'
import json, sys
path = sys.argv[1]
with open(path) as f:
    data = json.load(f)
data["attribution"] = {"commit": "", "pr": "", "sessionUrl": False}
# Autocompact at 50% of the context window (global/agent-rules.md).
data.setdefault("env", {})["CLAUDE_AUTOCOMPACT_PCT_OVERRIDE"] = "50"

# Session hooks that keep project agent files in murpiano-dx. Old entries are replaced.
sync = sys.argv[2]
hooks = data.setdefault("hooks", {})
for event, mode in (("SessionStart", "start"), ("SessionEnd", "end")):
    groups = [
        g for g in hooks.get(event, [])
        if not any(sync in h.get("command", "") for h in g.get("hooks", []))
    ]
    groups.append({"hooks": [{"type": "command", "command": f'bash "{sync}" {mode}', "timeout": 60}]})
    hooks[event] = groups
with open(path, "w") as f:
    json.dump(data, f, indent=2, ensure_ascii=False)
    f.write("\n")
PY
echo "updated $settings"

echo "== Global agent rules"
# Rule block goes between markers into each agent's global instruction file. Old block is replaced.
rules="$root/global/agent-rules.md"
begin='<!-- >>> murpiano-dx -->'
end='<!-- <<< murpiano-dx -->'
for file in "$HOME/.claude/CLAUDE.md"; do
  mkdir -p "$(dirname "$file")"
  touch "$file"
  sed -i "/^$begin\$/,/^$end\$/d" "$file"
  { echo "$begin"; cat "$rules"; echo "$end"; } >>"$file"
  echo "updated $file"
done
